// Generates src/shared/time/timeZoneCountries.generated.ts: IANA time zone id → ISO country code.
// Browsers do not expose which country a zone belongs to; the tz database does (public domain):
//   zone.tab   one line per canonical zone: "BR  -2332-04637  America/Sao_Paulo"
//   tzdata.zi  "L <canonical> <alias>" lines for legacy names (e.g. Asia/Calcutta → Asia/Kolkata)
// Run when the tz database changes: node scripts/generate-time-zone-countries.mjs [/usr/share/zoneinfo]
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const zoneInfoDirectory = process.argv[2] ?? "/usr/share/zoneinfo";
const outputPath = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../src/shared/time/timeZoneCountries.generated.ts");

const countryCodeByZone = new Map();
for (const zoneLine of readFileSync(path.join(zoneInfoDirectory, "zone.tab"), "utf8").split("\n")) {
  if (!zoneLine || zoneLine.startsWith("#")) continue;
  const [countryCode, , timeZoneId] = zoneLine.split("\t");
  countryCodeByZone.set(timeZoneId, countryCode);
}

for (const zoneDataLine of readFileSync(path.join(zoneInfoDirectory, "tzdata.zi"), "utf8").split("\n")) {
  if (!zoneDataLine.startsWith("L ")) continue;
  const [, canonicalZoneId, aliasZoneId] = zoneDataLine.split(" ");
  const canonicalCountryCode = countryCodeByZone.get(canonicalZoneId);
  if (canonicalCountryCode && !countryCodeByZone.has(aliasZoneId)) countryCodeByZone.set(aliasZoneId, canonicalCountryCode);
}

const sortedEntries = [...countryCodeByZone.entries()].sort(([firstZoneId], [secondZoneId]) => firstZoneId.localeCompare(secondZoneId));
const generatedSource = `// Generated by scripts/generate-time-zone-countries.mjs from the tz database (public domain).
// Do not edit by hand: run "node scripts/generate-time-zone-countries.mjs".
export const countryCodeByTimeZone: Readonly<Record<string, string>> = {
${sortedEntries.map(([timeZoneId, countryCode]) => `  "${timeZoneId}": "${countryCode}",`).join("\n")}
};
`;
writeFileSync(outputPath, generatedSource);
console.log(`wrote ${sortedEntries.length} zones to ${path.relative(process.cwd(), outputPath)}`);
