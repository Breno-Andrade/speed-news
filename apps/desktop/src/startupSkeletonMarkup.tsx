import { renderToStaticMarkup } from "react-dom/server";
import { StartupSkeleton, STATIC_SKELETON_LABEL } from "./StartupSkeleton";

/** Markers around the startup skeleton inlined in index.html. */
export const STARTUP_SKELETON_START = "<!-- startup-skeleton: generated by `npm run generate:startup-skeleton`, do not edit -->";
export const STARTUP_SKELETON_END = "<!-- /startup-skeleton -->";

/** The HTML index.html must carry inside #root (used by the generator script and by a test). */
export function renderStartupSkeletonMarkup(): string {
  return renderToStaticMarkup(<StartupSkeleton label={STATIC_SKELETON_LABEL} />);
}

/** index.html with the block between the markers replaced by the current skeleton. */
export function withStartupSkeleton(indexHtml: string): string {
  const startIndex = indexHtml.indexOf(STARTUP_SKELETON_START);
  const endIndex = indexHtml.indexOf(STARTUP_SKELETON_END);
  if (startIndex < 0 || endIndex < startIndex) throw new Error("index.html has no startup skeleton markers");
  return (
    indexHtml.slice(0, startIndex + STARTUP_SKELETON_START.length) +
    renderStartupSkeletonMarkup() +
    indexHtml.slice(endIndex)
  );
}
