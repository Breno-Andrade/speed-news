//! Tray icon, tooltip and menu, drawn from the state the Go sidecar reports (sidecar.rs). The
//! popover webview is not involved, so the tray stays current while the webview is destroyed.
//!
//! - macOS: the count is native text next to the menu bar icon (`TrayIcon::set_title`); the icon
//!   is a template image the system tints for light and dark menu bars.
//! - Linux and Windows: the icon switches to a red-dot variant when there is something unread;
//!   the exact count is shown in the popover header and in the tooltip. (Linux uses the ksni
//!   backend for left clicks, and ksni cannot show text next to the icon.)
//! - Windows: the symbol is white on dark taskbars and dark on light ones.
//!
//! Clicks: left click toggles the popover, right click shows the menu. On Linux this needs the
//! `ksni` tray backend (see Cargo.toml): the default AppIndicator backend turns every click into
//! "open the menu" and never tells the app.

use std::sync::Mutex;

use serde::Deserialize;
use tauri::image::Image;
use tauri::menu::{Menu, MenuItem};
use tauri::tray::{MouseButton, MouseButtonState, TrayIconBuilder, TrayIconEvent};
use tauri::{AppHandle, Manager, Wry};

use crate::placement::ScreenRect;
use crate::popover;
use crate::tray_texts::{system_locale, tray_texts};

const TRAY_ID: &str = "speed-news-tray";
const OPEN_MENU_ID: &str = "open";
const QUIT_MENU_ID: &str = "quit";

// Generated by tools/icon-generator (`make icons`): keep the names in sync with trayIconFiles().
const TRAY_ICON_LIGHT: &[u8] = include_bytes!("../icons/tray/tray-light.png");
const TRAY_ICON_LIGHT_UNREAD: &[u8] = include_bytes!("../icons/tray/tray-light-unread.png");
const TRAY_ICON_DARK: &[u8] = include_bytes!("../icons/tray/tray-dark.png");
const TRAY_ICON_DARK_UNREAD: &[u8] = include_bytes!("../icons/tray/tray-dark-unread.png");

/// One `SPEED_NEWS_TRAY` line of the sidecar (Go: shellbridge.TrayState). Missing fields take
/// defaults so an older or newer sidecar never breaks the tray.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
#[serde(rename_all = "camelCase", default)]
pub struct SidecarTrayState {
    pub unread_count: u32,
    pub show_unread_indicator: bool,
    pub interface_language: String,
    pub close_on_focus_loss: bool,
}

impl Default for SidecarTrayState {
    fn default() -> Self {
        Self {
            unread_count: 0,
            show_unread_indicator: true,
            interface_language: "system".into(),
            close_on_focus_loss: true,
        }
    }
}

impl SidecarTrayState {
    /// What the icon (and the GNOME panel button) show: nothing when the user turned the
    /// indicator off. The tooltip keeps the real count.
    fn indicated_count(&self) -> u32 {
        if self.show_unread_indicator {
            self.unread_count
        } else {
            0
        }
    }
}

/// Last state from the sidecar plus the locale the UI detected for "system" (it may know better
/// than the environment, e.g. on macOS).
#[derive(Default)]
pub struct TrayModel {
    latest_state: Mutex<SidecarTrayState>,
    locale_reported_by_ui: Mutex<Option<String>>,
}

/// Kept so the entries can be renamed when the interface language changes.
struct TrayMenuItems {
    open_menu_item: MenuItem<Wry>,
    quit_menu_item: MenuItem<Wry>,
}

pub fn create_tray(application_handle: &AppHandle) -> tauri::Result<()> {
    let initial_texts = tray_texts(0, "system", &system_locale());
    // On Linux a left click usually does not reach the app (AppIndicator limitation),
    // so the menu always offers an explicit "open" entry.
    let open_menu_item = MenuItem::with_id(
        application_handle,
        OPEN_MENU_ID,
        initial_texts.open_label,
        true,
        None::<&str>,
    )?;
    let quit_menu_item = MenuItem::with_id(
        application_handle,
        QUIT_MENU_ID,
        initial_texts.quit_label,
        true,
        None::<&str>,
    )?;
    let tray_menu = Menu::with_items(application_handle, &[&open_menu_item, &quit_menu_item])?;
    application_handle.manage(TrayMenuItems {
        open_menu_item: open_menu_item.clone(),
        quit_menu_item: quit_menu_item.clone(),
    });

    TrayIconBuilder::with_id(TRAY_ID)
        .icon(Image::from_bytes(tray_icon_bytes(false, uses_dark_symbol()))?)
        .icon_as_template(cfg!(target_os = "macos"))
        .tooltip(initial_texts.tooltip)
        .menu(&tray_menu)
        .show_menu_on_left_click(false)
        .on_menu_event(|application_handle, menu_event| match menu_event.id().as_ref() {
            OPEN_MENU_ID => popover::show_popover(application_handle, None),
            QUIT_MENU_ID => application_handle.exit(0),
            _ => {}
        })
        .on_tray_icon_event(|tray_icon, tray_event| {
            let (event_position, event_rect) = match &tray_event {
                TrayIconEvent::Click { position, rect, .. }
                | TrayIconEvent::DoubleClick { position, rect, .. }
                | TrayIconEvent::Enter { position, rect, .. }
                | TrayIconEvent::Move { position, rect, .. }
                | TrayIconEvent::Leave { position, rect, .. } => (*position, *rect),
                _ => return,
            };
            let icon_area = tray_icon_area(event_rect);
            if let Some(icon_area) = icon_area {
                tray_icon
                    .app_handle()
                    .state::<popover::PopoverState>()
                    .remember_tray_icon_area(icon_area);
            }
            if let TrayIconEvent::Click {
                button: MouseButton::Left,
                button_state: MouseButtonState::Up,
                ..
            } = tray_event
            {
                popover::toggle_popover(tray_icon.app_handle(), click_anchor(icon_area, event_position));
            }
        })
        .build(application_handle)?;

    #[cfg(target_os = "windows")]
    watch_taskbar_theme(application_handle);
    Ok(())
}

/// Called for every tray line of the sidecar.
pub fn apply_sidecar_state(application_handle: &AppHandle, sidecar_state: SidecarTrayState) {
    application_handle
        .state::<popover::PopoverState>()
        .set_close_on_focus_loss(sidecar_state.close_on_focus_loss);
    if let Ok(mut state_guard) = application_handle.state::<TrayModel>().latest_state.lock() {
        *state_guard = sidecar_state;
    }
    // Lines arrive on the sidecar reader task; tray, menu and D-Bus updates belong on the main
    // thread, where the former `update_tray` command ran.
    let refreshing_application_handle = application_handle.clone();
    let _ = application_handle.run_on_main_thread(move || refresh_tray(&refreshing_application_handle));
}

/// The UI reports the locale it detected for "system", so tray and popover agree.
#[tauri::command]
pub fn report_system_locale(application_handle: AppHandle, system_locale: String) {
    if let Ok(mut locale_guard) = application_handle.state::<TrayModel>().locale_reported_by_ui.lock() {
        *locale_guard = Some(system_locale);
    }
    refresh_tray(&application_handle);
}

/// Hidden while the GNOME panel button is active, so the app does not appear twice.
pub fn set_tray_visible(application_handle: &AppHandle, is_visible: bool) {
    if let Some(tray_icon) = application_handle.tray_by_id(TRAY_ID) {
        let _ = tray_icon.set_visible(is_visible);
    }
}

fn refresh_tray(application_handle: &AppHandle) {
    let tray_model = application_handle.state::<TrayModel>();
    let Ok(sidecar_state) = tray_model.latest_state.lock().map(|state_guard| state_guard.clone()) else {
        return;
    };
    let effective_system_locale = tray_model
        .locale_reported_by_ui
        .lock()
        .ok()
        .and_then(|locale_guard| locale_guard.clone())
        .unwrap_or_else(system_locale);
    let texts = tray_texts(
        sidecar_state.unread_count,
        &sidecar_state.interface_language,
        &effective_system_locale,
    );
    let indicated_count = sidecar_state.indicated_count();

    if let Some(tray_icon) = application_handle.tray_by_id(TRAY_ID) {
        // macOS: native text next to the menu bar icon.
        #[cfg(target_os = "macos")]
        let _ = tray_icon.set_title((indicated_count > 0).then(|| indicated_count.to_string()));

        // Linux and Windows: only "has unread" vs "all read" on the icon itself.
        #[cfg(not(target_os = "macos"))]
        if let Ok(state_icon) = Image::from_bytes(tray_icon_bytes(indicated_count > 0, uses_dark_symbol())) {
            let _ = tray_icon.set_icon(Some(state_icon));
        }
        let _ = tray_icon.set_tooltip(Some(texts.tooltip));
    }

    // Keep the GNOME panel button (if any) in sync.
    #[cfg(target_os = "linux")]
    crate::panel_bridge::publish_tray_state(application_handle, indicated_count, texts.open_label, texts.quit_label);

    let tray_menu_items = application_handle.state::<TrayMenuItems>();
    let _ = tray_menu_items.open_menu_item.set_text(texts.open_label);
    let _ = tray_menu_items.quit_menu_item.set_text(texts.quit_label);
}

/// The icon's area in physical pixels; None when the backend does not report it (ksni gives
/// an empty rectangle).
fn tray_icon_area(event_rect: tauri::Rect) -> Option<ScreenRect> {
    let icon_position = event_rect.position.to_physical::<i32>(1.0);
    let icon_size = event_rect.size.to_physical::<u32>(1.0);
    (icon_size.width > 0 && icon_size.height > 0).then(|| {
        ScreenRect::new(
            icon_position.x,
            icon_position.y,
            icon_size.width as i32,
            icon_size.height as i32,
        )
    })
}

/// What the popover opens next to: the icon's area (Windows/macOS), else the click point (ksni
/// reports it, KDE for instance), else nothing. Some StatusNotifier hosts send (0, 0) for
/// "unknown"; that is not a real click position.
fn click_anchor(icon_area: Option<ScreenRect>, click_position: tauri::PhysicalPosition<f64>) -> Option<ScreenRect> {
    icon_area.or_else(|| {
        let has_click_position = click_position.x != 0.0 || click_position.y != 0.0;
        has_click_position.then(|| ScreenRect::point(click_position.x as i32, click_position.y as i32))
    })
}

/// Picks the generated PNG for a state. Pure, so it is unit tested.
fn tray_icon_bytes(has_unread: bool, uses_dark_symbol: bool) -> &'static [u8] {
    match (uses_dark_symbol, has_unread) {
        (false, false) => TRAY_ICON_LIGHT,
        (false, true) => TRAY_ICON_LIGHT_UNREAD,
        (true, false) => TRAY_ICON_DARK,
        (true, true) => TRAY_ICON_DARK_UNREAD,
    }
}

/// Dark symbol on light Windows taskbars and for the macOS template image (only its alpha
/// counts there). Linux panels (GNOME, KDE defaults) are dark: white symbol, like the GNOME button.
#[cfg(target_os = "windows")]
fn uses_dark_symbol() -> bool {
    windows_taskbar_is_light()
}

#[cfg(target_os = "macos")]
fn uses_dark_symbol() -> bool {
    true
}

#[cfg(target_os = "linux")]
fn uses_dark_symbol() -> bool {
    false
}

/// Windows 10/11 "Choose your default Windows mode" (taskbar). Missing key = dark (the default).
#[cfg(target_os = "windows")]
fn windows_taskbar_is_light() -> bool {
    windows_registry::CURRENT_USER
        .open(r"Software\Microsoft\Windows\CurrentVersion\Themes\Personalize")
        .and_then(|personalize_key| personalize_key.get_u32("SystemUsesLightTheme"))
        .map(|uses_light_theme| uses_light_theme == 1)
        .unwrap_or(false)
}

/// No window exists to receive theme change events most of the time, so the taskbar theme is
/// read again once a minute (one registry read) and the icon redrawn when it changed.
#[cfg(target_os = "windows")]
fn watch_taskbar_theme(application_handle: &AppHandle) {
    const THEME_CHECK_INTERVAL: std::time::Duration = std::time::Duration::from_secs(60);
    let watching_application_handle = application_handle.clone();
    std::thread::spawn(move || {
        let mut was_light = windows_taskbar_is_light();
        loop {
            std::thread::sleep(THEME_CHECK_INTERVAL);
            let is_light = windows_taskbar_is_light();
            if is_light != was_light {
                was_light = is_light;
                let redrawing_application_handle = watching_application_handle.clone();
                let _ =
                    watching_application_handle.run_on_main_thread(move || refresh_tray(&redrawing_application_handle));
            }
        }
    });
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn indicator_off_hides_the_count_on_the_icon_only() {
        let sidecar_state = SidecarTrayState {
            unread_count: 7,
            show_unread_indicator: false,
            ..SidecarTrayState::default()
        };
        assert_eq!(sidecar_state.indicated_count(), 0);
        // The tooltip is built from unread_count, which keeps the real number.
        assert_eq!(
            tray_texts(sidecar_state.unread_count, "en", "en").tooltip,
            "Speed News — 7 unread"
        );
    }

    #[test]
    fn indicator_on_shows_the_count() {
        let sidecar_state = SidecarTrayState {
            unread_count: 3,
            ..SidecarTrayState::default()
        };
        assert_eq!(sidecar_state.indicated_count(), 3);
    }

    #[test]
    fn every_icon_variant_is_a_distinct_png() {
        let variants = [
            tray_icon_bytes(false, false),
            tray_icon_bytes(true, false),
            tray_icon_bytes(false, true),
            tray_icon_bytes(true, true),
        ];
        for (variant_index, variant_bytes) in variants.iter().enumerate() {
            assert!(
                Image::from_bytes(variant_bytes).is_ok(),
                "variant {variant_index} must decode"
            );
            for other_bytes in &variants[variant_index + 1..] {
                assert_ne!(variant_bytes, other_bytes);
            }
        }
    }

    #[test]
    fn icon_area_comes_from_the_reported_rectangle() {
        let reported_rect = tauri::Rect {
            position: tauri::PhysicalPosition::new(1700, 1040).into(),
            size: tauri::PhysicalSize::new(24, 24).into(),
        };
        assert_eq!(tray_icon_area(reported_rect), Some(ScreenRect::new(1700, 1040, 24, 24)));
        // ksni: empty rectangle, no area.
        assert_eq!(tray_icon_area(tauri::Rect::default()), None);
    }

    #[test]
    fn click_anchor_prefers_the_icon_area_then_the_click_point() {
        let icon_area = ScreenRect::new(1700, 1040, 24, 24);
        assert_eq!(
            click_anchor(Some(icon_area), tauri::PhysicalPosition::new(5.0, 5.0)),
            Some(icon_area)
        );
        assert_eq!(
            click_anchor(None, tauri::PhysicalPosition::new(3700.0, 12.0)),
            Some(ScreenRect::point(3700, 12))
        );
        // (0, 0) means "position unknown" for some StatusNotifier hosts.
        assert_eq!(click_anchor(None, tauri::PhysicalPosition::new(0.0, 0.0)), None);
    }

    #[test]
    fn missing_fields_take_defaults() {
        let sidecar_state: SidecarTrayState = serde_json::from_str(r#"{"unreadCount":2}"#).unwrap();
        assert_eq!(
            sidecar_state,
            SidecarTrayState {
                unread_count: 2,
                ..SidecarTrayState::default()
            }
        );
    }
}
